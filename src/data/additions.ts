export const getAdditionById = (id: string): Addition | undefined =>
  ADDITIONS.find((a) => a.id === id)

export const getAdditionsByCategory = (categoryId: string): Addition[] =>
  ADDITIONS.filter((a) => a.categoryId === categoryId)

export const searchAdditions = (query: string): Addition[] => {
  const q = query.toLowerCase()
  return ADDITIONS.filter(
    (a) =>
      a.name.toLowerCase().includes(q) ||
      a.plainDescription.toLowerCase().includes(q) ||
      a.description.toLowerCase().includes(q) ||
      a.tags?.some((t) => t.toLowerCase().includes(q))
  )
}
